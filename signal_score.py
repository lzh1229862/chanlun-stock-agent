"""signal_score.py —— 信号排序打分（T19 / ADR-023）。

    score = [最近中枢宽度 >= 0.12] + [距中枢结束 < 10 个交易日]      -> 0 / 1 / 2

### 实测（4135 条 / 45 只 / 11 年）

| 窗口 | score=2 | score=1 | score=0 | score2 − score0 | 95%CI | 分半 |
| --- | --- | --- | --- | --- | --- | --- |
| 5 日 | +3.23% (n=563) | +1.12% | +0.65% (n=450) | **+2.58%** | [+1.76%, +3.41%] | +2.50% / +2.70% |
| 10 日 | +3.42% | +1.03% | +0.56% | **+2.86%** | [+1.72%, +4.00%] | +3.44% / +1.96% |
| 20 日 | +3.90% | +0.62% | +0.48% | **+3.42%** | [+1.55%, +5.29%] | +4.30% / +2.13% |

**三个窗口 CI 全不跨 0、分半全一致、且单调（2 > 1 > 0）。**

### ⚠️ 这条结论是**探索性**的，不是预注册验证过的

两个因子各自经过了预注册验证（H3 在第 1 轮成立；中枢宽度是 LLM 预测反了、但数据支持的），
但**「把它们加起来」这个动作是看到结果之后才定的，没有预注册**。

按本项目的纪律（ADR-021），它要成为正式结论**必须再开一轮预注册**：
把 "score2 − score0 > 0" 写死在假设文件里，再检验一次。

在那之前：**可以用作展示时的排序提示，但不能当作战绩宣传，也不能据此调整仓位。**

### 两个因子的稳健性并不相同

- **中枢宽度**：阈值 0.03~0.20 **八个档 CI 全部不跨 0**，效应量随阈值上升（+0.80% → +2.21%）。
  跨窗口 CI 也全不跨 0。**这是项目里最稳健的因子。**
- **距中枢距离（H3）**：只有 5 日窗口 CI 不跨 0；10/20 日方向一致但 CI 跨 0。
  阈值在 8~15 是一段平台（效应量 −0.4~−0.6%），但 **≥5 会符号反转**，不是干净的单向关系。
"""

W_THR = 0.12   # 中枢宽度阈值（H4 用的就是它，且 0.10~0.15 都在有效区间内）
G_THR = 10     # 距中枢结束天数阈值（H3 用的就是它，8~15 是平台）


def score_of(zs_width_pct, zs_gap_days):
    """0 / 1 / 2。缺数据的因子记 0 分（不能因为「不知道」就给正面评价）。"""
    s = 0
    try:
        if zs_width_pct is not None and float(zs_width_pct) >= W_THR:
            s += 1
        if zs_gap_days is not None and 0 <= float(zs_gap_days) < G_THR:
            s += 1
    except (TypeError, ValueError):
        return 0
    return s


def label_of(score):
    return {2: "★★", 1: "★", 0: "—"}.get(score, "—")


def note_of(score):
    if score == 2:
        return "两个有利条件都满足（中枢较宽 + 离中枢近）"
    if score == 1:
        return "满足一个有利条件"
    return "两个有利条件都不满足"
